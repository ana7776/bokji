function makePost({ id, slug, title, description, summary, category, tags, featured, publishedAt, sections }) {
  const body = sections.map(([heading, ...paragraphs]) => ({ heading, paragraphs }));
  return {
    id,
    slug,
    title,
    description,
    summary,
    category,
    tags,
    featured,
    body,
    publishedAt,
    updatedAt: publishedAt,
    status: "published",
    path: `/posts/${slug}/`,
    image: `/assets/posts/${slug}.webp`
  };
}

